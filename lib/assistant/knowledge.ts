export interface AssistantResponse {
  answer: string;
  source: string;
  sourceUrl?: string;
  relatedAction?: {
    label: string;
    href: string;
  };
  suggestedFollowUps?: string[];
}

export function askAssistant(question: string): AssistantResponse {
  const q = question.toLowerCase().trim();

  // 1. Пособия на второго ребенка
  if (q.includes('втор') || q.includes('другог') || q.includes('пособи') && q.includes('2')) {
    return {
      answer: `При рождении **второго ребёнка** в Республике Беларусь семья имеет право на следующие государственные выплаты:\n\n1. **Единовременное пособие в связи с рождением**: **14 БПМ (6 129,20 BYN)**.\n2. **Пособие за постановку на учёт до 12 недель**: **100% БПМ (437,80 BYN)**.\n3. **Ежемесячное пособие по уходу за ребёнком до 3 лет**: **40% СЗП (966,30 BYN/месяц)**.\n4. **Ежемесячное пособие на старшего ребёнка (до 18 лет)** в период воспитания малыша до 3 лет: **50% БПМ (218,90 BYN/месяц)**.\n\n*Выплаты оформляются по основному месту работы матери или отца, либо в управлении по труду и соцзащите (УТЗСН).*`,
      source: 'Закон Республики Беларусь № 7-З «О государственных пособиях семьям, воспитывающим детей»',
      sourceUrl: 'https://mintrud.gov.by',
      relatedAction: {
        label: 'Рассчитать точную сумму в калькуляторе',
        href: '/benefits'
      },
      suggestedFollowUps: [
        'Какие документы нужны для оформления пособия?',
        'Как оформить пособие на старшего ребенка от 3 до 18 лет?',
        'Как встать на очередь в детский сад?'
      ]
    };
  }

  // 2. Семейный капитал
  if (q.includes('капитал') || q.includes('многодетн') || q.includes('трет') || q.includes('трэц')) {
    return {
      answer: `**Семейный капитал** в Беларуси назначается при рождении (усыновлении) **третьего или последующих детей**.\n\n- Размер: **31 426,00 BYN** (сумма ежегодно индексируется государством).\n- Средства зачисляются во вклад в ОАО «АСБ Беларусбанк».\n- **Досрочное использование разрешено на**:\n  • Строительство, реконструкцию или покупку жилья, погашение жилищных кредитов;\n  • Получение высшего или среднего специального образования в государственных вузах РБ;\n  • Оплату медицинских услуг (стоматология, кардиохирургия, ортопедия).\n\n*Заявление необходимо подать в райисполком по месту жительства в течение 6 месяцев с даты рождения ребенка.*`,
      source: 'Указ Президента Республики Беларусь № 345 «О семейном капитале»',
      sourceUrl: 'https://belarusbank.by',
      relatedAction: {
        label: 'Инструкция по семейному капиталу',
        href: '/benefits'
      },
      suggestedFollowUps: [
        'Как досрочно использовать семейный капитал на жилье?',
        'Какие льготы положены многодетной семье в детском саду?',
        'Как получить удостоверение многодетной семьи?'
      ]
    };
  }

  // 3. Детский сад / Очередь
  if (q.includes('сад') || q.includes('садик') || q.includes('очередь') || q.includes('садок')) {
    return {
      answer: `Чтобы **встать на очередь в детский сад** в Республике Беларусь:\n\n1. Получите свидетельство о рождении ребенка в ЗАГСе.\n2. Обратитесь в службу **«Одно окно»** администрации района по месту жительства или регистрации.\n3. Предоставьте: **паспорт одного из родителей** и **свидетельство о рождении ребёнка**.\n4. Назовите желаемые номера дошкольных учреждений (рекомендуется указать 2-3 приоритетных детских сада).\n5. Ребенку присваивается учетный номер в единой электронной базе, и вы получаете уведомление о регистрации.`,
      source: 'Министерство образования Республики Беларусь (Кодекс об образовании)',
      sourceUrl: 'https://edu.gov.by',
      relatedAction: {
        label: 'Найти детский сад на карте Минска и РБ',
        href: '/infrastructure'
      },
      suggestedFollowUps: [
        'Как подготовить ребенка к адаптации в саду?',
        'Сколько стоит питание в детском саду?',
        'Есть ли льготы на детский сад для многодетных?'
      ]
    };
  }

  // 4. Психологическая помощь / Кризис / Насилие / SOS
  if (q.includes('кризис') || q.includes('насил') || q.includes('sos') || q.includes('помощ') || q.includes('психолог') || q.includes('выгоран')) {
    return {
      answer: `Вам оказывается **полная конфиденциальная и бесплатная помощь**:\n\n- **Республиканская горячая линия для пострадавших от домашнего насилия**: **8-801-100-8801** (бесплатно со стационарных и мобильных телефонов РБ, ежедневно с 8:00 до 20:00).\n- **Детская телефонная линия (кризисная поддержка для детей и родителей)**: **8-801-100-1611** (круглосуточно 24/7).\n- **Кризисные комнаты ТЦСОН**: предоставляют временное бесплатное безопасное проживание для мамы с детьми в любом районе Беларуси.\n- **Онлайн-консультация психолога**: доступна непосредственно в нашей платформе «Родныя».`,
      source: 'Министерство труда и социальной защиты РБ & МВД Республики Беларусь',
      sourceUrl: 'https://mintrud.gov.by',
      relatedAction: {
        label: 'Открыть экстренный раздел «Семейный щит»',
        href: '/psychology'
      },
      suggestedFollowUps: [
        'Как связаться с дежурным психологом прямо сейчас?',
        'Где находится ближайшая кризисная комната?',
        'Упражнения для снятия стресса и паники'
      ]
    };
  }

  // 5. Беременность / срок / женская консультация
  if (q.includes('беременност') || q.includes('срок') || q.includes('родов') || q.includes('узи') || q.includes('скрининг')) {
    return {
      answer: `Срок беременности рассчитывается **по первому дню последней менструации (LMP)**:\n\n- Нормальная доношенная беременность длится **40 акушерских недель (280 дней)**.\n- Предполагаемая дата родов (ПДР) вычисляется по формуле Негеле: **+1 год - 3 месяца + 7 дней** от даты начала последней менструации.\n- **Обязательные скрининги в Беларуси**:\n  • **11–13 недель 6 дней**: первый УЗИ скрининг + биохимический тест на генетические аномалии;\n  • **19–21 неделя**: второй детальный анатомический скрининг внутренних органов плода;\n  • **30 недель**: оформление больничного листа по беременности и родам в женской консультации.`,
      source: 'Клинические протоколы Министерства здравоохранения Республики Беларусь',
      sourceUrl: 'https://minzdrav.gov.by',
      relatedAction: {
        label: 'Открыть персональный календарь беременности',
        href: '/health'
      },
      suggestedFollowUps: [
        'Как получить единовременную выплату за учет до 12 недель?',
        'Что взять с собой в роддом?',
        'Календарь обязательных анализов'
      ]
    };
  }

  // 6. Питание «Беллакт» / Адресная социальная помощь
  if (q.includes('беллакт') || q.includes('питан') || q.includes('адресн') || q.includes('малообеспеч')) {
    return {
      answer: `**Бесплатное обеспечение детским питанием детей первых двух лет жизни** предоставляется:\n\n1. Семьям, чей среднедушевой доход не превышает **100% БПМ (437,80 BYN)**.\n2. При одновременном рождении **двойни, тройни и более детей** питание предоставляется **независимо от уровня доходов семьи**!\n\nВыдаются высококачественные продукты отечественного производства (ОАО «Беллакт»): сухие адаптированные смеси, каши, овощные и мясные пюре, соки.\nЗаявление подается в орган по труду и соцзащите по заключению участкового педиатра.`,
      source: 'Указ Президента Республики Беларусь № 41 «О государственной адресной социальной помощи»',
      sourceUrl: 'https://mintrud.gov.by',
      relatedAction: {
        label: 'Перейти к перечню пособий',
        href: '/benefits'
      }
    };
  }

  // Ответ по умолчанию с умной структуризацией
  return {
    answer: `Здравствуйте! Я — цифровой помощник экосистемы **«Родныя»**.\n\nЯ могу помочь вам по всем вопросам поддержки семьи в Республике Беларусь:\n\n• **Расчёт государственных пособий** (при рождении, до 3 лет, семейный капитал, льготы).\n• **Чек-листы оформления документов** в ЗАГСе, исполкомах и службе «Одно окно».\n• **Календарь беременности** и график скринингов Минздрава РБ.\n• **Поиск детских садов**, поликлиник и доступной среды на интерактивной карте.\n• **Психологическая поддержка** и контакты горячих линий помощи семье.\n\nЗадайте ваш вопрос или выберите одну из подсказок ниже!`,
    source: 'Цифровая платформа «Родныя» (Законодательство Республики Беларусь)',
    sourceUrl: 'https://mintrud.gov.by',
    suggestedFollowUps: [
      'Какие пособия положены при рождении второго ребенка?',
      'Как оформить семейный капитал?',
      'Как встать на очередь в детский сад?',
      'Как рассчитать срок беременности?'
    ]
  };
}
