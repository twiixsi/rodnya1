    'accessible_space', 
    'maternity_store', 
    'development_center', 
    'hobby_club', 
    'one_window', 
    'leisure_food'
  ));

-- 4. Включаем RLS (Row Level Security) и даем публичный доступ на чтение
ALTER TABLE public.institutions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read access on institutions" ON public.institutions;
