ALTER TABLE public.profiles ALTER COLUMN role SET DEFAULT 'user';

-- 2. ТАБЛИЦА УЧРЕЖДЕНИЙ (ИНФРАСТРУКТУРА)
CREATE TABLE IF NOT EXISTS public.institutions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    address TEXT NOT NULL,
    city TEXT NOT NULL DEFAULT 'г. Минск',
    district TEXT NOT NULL DEFAULT 'Центральный район',
    region TEXT NOT NULL DEFAULT 'г. Минск',
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    phone TEXT NOT NULL,
    work_hours TEXT NOT NULL,
    description TEXT NOT NULL,
    image_url TEXT NOT NULL,
    free_spots INT DEFAULT 0,
    free_spots_nursery INT DEFAULT 0,
    free_spots_garden INT DEFAULT 0,
    age_range TEXT,
    groups_info TEXT,
    specialties JSONB DEFAULT '[]'::jsonb,
    tags JSONB DEFAULT '[]'::jsonb,
    has_ramp BOOLEAN DEFAULT FALSE,
    has_elevator BOOLEAN DEFAULT FALSE,
    has_mother_child_room BOOLEAN DEFAULT FALSE,
    rating NUMERIC(3, 2) DEFAULT 4.9,
    reviews_count INT DEFAULT 10,
    badge_text TEXT,
    website_url TEXT,
    admin_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    admin_name TEXT,
    admin_role TEXT,
    has_online_admin BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Добавляем колонки, если таблица уже существовала в базе
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS tags JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS specialties JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS groups_info TEXT;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS badge_text TEXT;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS free_spots_nursery INT DEFAULT 0;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS free_spots_garden INT DEFAULT 0;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS age_range TEXT;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS admin_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS admin_name TEXT;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS admin_role TEXT;
ALTER TABLE public.institutions ADD COLUMN IF NOT EXISTS has_online_admin BOOLEAN DEFAULT FALSE;

-- Снимаем старый CHECK constraint на type, чтобы не было конфликтов
ALTER TABLE public.institutions DROP CONSTRAINT IF EXISTS institutions_type_check;

-- 3. ВКЛЮЧАЕМ ПУБЛИЧНЫЙ ДОСТУП НА ЧТЕНИЕ
ALTER TABLE public.institutions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read access on institutions" ON public.institutions;
CREATE POLICY "Allow public read access on institutions" 
  ON public.institutions FOR SELECT USING (true);

-- 4. ТАБЛИЦА ЭЛЕКТРОННЫХ ЗАЯВОК В САДИКИ (ДЛЯ АДМИНА САДА И РОДИТЕЛЕЙ)
CREATE TABLE IF NOT EXISTS public.kindergarten_applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    child_name TEXT NOT NULL,
    parent_name TEXT NOT NULL,
    parent_phone TEXT NOT NULL,
    target_institution_id UUID REFERENCES public.institutions(id) ON DELETE CASCADE,
    target_institution_name TEXT NOT NULL,
    application_number TEXT NOT NULL,
    group_type TEXT DEFAULT 'nursery', -- ясли, младшая, средняя
    status TEXT NOT NULL DEFAULT 'pending', -- 'pending' (на рассмотрении), 'approved' (одобрено), 'rejected' (отклонено)
    admin_comment TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.kindergarten_applications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow users and admins access to applications" ON public.kindergarten_applications;
CREATE POLICY "Allow users and admins access to applications" 
  ON public.kindergarten_applications FOR ALL USING (true);

-- 5. ТАБЛИЦА ЗАПИСЕЙ В КРУЖКИ И СЕКЦИИ (ДЛЯ АДМИНА КРУЖКА)
CREATE TABLE IF NOT EXISTS public.hobby_enrollments (
