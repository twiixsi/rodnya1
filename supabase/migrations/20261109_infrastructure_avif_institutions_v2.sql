-- 1. НАСТРОЙКА РОЛЕЙ ПОЛЬЗОВАТЕЛЕЙ В ТАБЛИЦЕ PROFILES
-- Переводим колонку role в тип TEXT, чтобы в Supabase Table Editor можно было свободно указывать любую роль
DO $$ 
BEGIN
  ALTER TABLE public.profiles ALTER COLUMN role TYPE TEXT USING role::TEXT;
